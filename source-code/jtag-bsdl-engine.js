/**
 * JTAGForge Pro - BSDL (Boundary Scan Description Language) & SVF Engine
 * Standards: IEEE 1149.1b BSDL Specification & Serial Vector Format (SVF)
 * Pure ES6+ Module - Zero External Runtime Dependencies
 */

(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.JTAGBSDLEngine = factory();
  }
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  class JTAGBSDLEngine {
    /**
     * Parses a standard BSDL (VHDL) file string
     */
    static parseBSDL(bsdlText) {
      if (!bsdlText || typeof bsdlText !== 'string') {
        throw new Error('BSDL content must be a valid non-empty string');
      }

      // Strip comments (-- comment)
      const clean = bsdlText.replace(/--.*/g, '');

      // 1. Entity name
      const entityMatch = clean.match(/entity\s+([A-Za-z0-9_]+)\s+is/i);
      const entityName = entityMatch ? entityMatch[1] : 'UNKNOWN_ENTITY';

      // 2. Instruction length
      const irLenMatch = clean.match(/INSTRUCTION_LENGTH\s+of\s+[A-Za-z0-9_]+\s*:\s*entity\s+is\s+(\d+)\s*;/i);
      const irLength = irLenMatch ? parseInt(irLenMatch[1], 10) : 5;

      // 3. Instruction opcodes
      const opcodes = {};
      const opcodeMatch = clean.match(/INSTRUCTION_OPCODE\s+of\s+[A-Za-z0-9_]+\s*:\s*entity\s+is\s*"([^"]+)"/i);
      if (opcodeMatch) {
        const entries = opcodeMatch[1].split(',');
        for (const entry of entries) {
          const parts = entry.trim().match(/([A-Za-z0-9_]+)\s*\(([01\s]+)\)/);
          if (parts) {
            const instrName = parts[1].toUpperCase();
            const bitStr = parts[2].replace(/\s+/g, '');
            opcodes[instrName] = {
              bits: bitStr,
              hex: '0x' + parseInt(bitStr, 2).toString(16).toUpperCase(),
              val: parseInt(bitStr, 2)
            };
          }
        }
      } else {
        // Defaults if omitted
        opcodes['BYPASS'] = { bits: '1'.repeat(irLength), hex: '0x' + ((1 << irLength) - 1).toString(16).toUpperCase() };
        opcodes['EXTEST'] = { bits: '0'.repeat(irLength), hex: '0x00' };
        opcodes['SAMPLE'] = { bits: '00001'.slice(-irLength), hex: '0x01' };
        opcodes['IDCODE'] = { bits: '00010'.slice(-irLength), hex: '0x02' };
      }

      // 4. IDCODE register
      let idcodeHex = null;
      const idcodeMatch = clean.match(/IDCODE_REGISTER\s+of\s+[A-Za-z0-9_]+\s*:\s*entity\s+is\s*([^\;]+);/i);
      if (idcodeMatch) {
        const bitChunks = idcodeMatch[1].match(/"([01\s]+)"/g);
        if (bitChunks) {
          const combinedBits = bitChunks.map(c => c.replace(/["\s]/g, '')).join('');
          if (combinedBits.length === 32) {
            idcodeHex = '0x' + parseInt(combinedBits, 2).toString(16).padStart(8, '0').toUpperCase();
          }
        }
      }

      // 5. Boundary register length
      const bndLenMatch = clean.match(/BOUNDARY_LENGTH\s+of\s+[A-Za-z0-9_]+\s*:\s*entity\s+is\s+(\d+)\s*;/i);
      const boundaryLength = bndLenMatch ? parseInt(bndLenMatch[1], 10) : 64;

      return {
        entityName,
        irLength,
        opcodes,
        idcodeHex,
        boundaryLength,
        hasBypass: !!opcodes['BYPASS'],
        hasExtest: !!opcodes['EXTEST'],
        hasSample: !!opcodes['SAMPLE'] || !!opcodes['SAMPLE_PRELOAD'],
        hasIdcode: !!opcodes['IDCODE']
      };
    }

    /**
     * Generates a template BSDL string for a generic chip
     */
    static createTemplateBSDL(chipName = 'GENERIC_FPGA_300', irLength = 5, idcodeHex = '0x09300093') {
      const idVal = parseInt(idcodeHex, 16) >>> 0;
      const idBits = idVal.toString(2).padStart(32, '0');
      const verBits = idBits.slice(0, 4);
      const partBits = idBits.slice(4, 20);
      const mfgBits = idBits.slice(20, 31);
      const bit0 = idBits.slice(31);

      return `-- ==============================================================================
-- BSDL Description File for ${chipName}
-- Generated by JTAGForge Pro (v1.0.0) | Standard: IEEE 1149.1b
-- ==============================================================================

entity ${chipName} is
  generic (PHYSICAL_PIN_MAP : string := "FBGA_256");

  port (
    TCK : in bit;
    TMS : in bit;
    TDI : in bit;
    TDO : out bit;
    TRST : in bit;
    IO_PINS : inout bit_vector(0 to 63)
  );

  use STD_1149_1_2001.all;

  attribute COMPONENT_CONFORMANCE of ${chipName} : entity is "STD_1149_1_2001";

  attribute INSTRUCTION_LENGTH of ${chipName} : entity is ${irLength};

  attribute INSTRUCTION_OPCODE of ${chipName} : entity is
    "BYPASS (${'1'.repeat(irLength)}), " &
    "EXTEST (${'0'.repeat(irLength)}), " &
    "SAMPLE (00001), " &
    "IDCODE (00010), " &
    "HIGHZ  (01010)";

  attribute IDCODE_REGISTER of ${chipName} : entity is
    "${verBits}" &              -- Version (4b)
    "${partBits}" &     -- Part Number (16b)
    "${mfgBits}" &       -- Manufacturer JEDEC (11b)
    "${bit0}";                           -- Mandatory Bit 0 = 1

  attribute BOUNDARY_LENGTH of ${chipName} : entity is 64;

end ${chipName};
`;
    }
  }

  return JTAGBSDLEngine;
});
